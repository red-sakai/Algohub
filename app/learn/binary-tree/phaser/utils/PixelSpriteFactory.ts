import * as Phaser from 'phaser';

export type PixelGrid = number[][];

export interface PixelSpriteConfig {
    pixelSize?: number;
    palette?: Record<number, number>;
}

export class PixelSpriteFactory {
    static createTexture(scene: Phaser.Scene, key: string, grid: PixelGrid, config: PixelSpriteConfig = {}) {
        if (scene.textures.exists(key)) return;

        const pixelSize = config.pixelSize || 4;
        const palette: Record<number, number | null> = config.palette || {
            0: null,       // Transparent
            1: 0xffffff,   // Main / Skin
            2: 0x888888,   // Secondary / Armor
            3: 0x000000,   // Outline
            4: 0xff0000,   // Accent / Eye
            5: 0x22c55e,   // Green
            6: 0x3b82f6,   // Blue
            7: 0xf97316,   // Orange
        };

        const rows = grid.length;
        const cols = grid[0].length;
        const width = cols * pixelSize;
        const height = rows * pixelSize;

        const graphics = scene.make.graphics({ x: 0, y: 0 });

        for (let y = 0; y < rows; y++) {
            for (let x = 0; x < cols; x++) {
                const colorCode = grid[y][x];
                if (colorCode !== 0 && palette[colorCode] !== undefined && palette[colorCode] !== null) {
                    graphics.fillStyle(palette[colorCode]!, 1);
                    graphics.fillRect(x * pixelSize, y * pixelSize, pixelSize, pixelSize);
                }
            }
        }

        graphics.generateTexture(key, width, height);
        graphics.destroy();
    }
}

